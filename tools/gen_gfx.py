#!/usr/bin/env python3
"""Generates Odin (and one JS list) from the Anvil world export art/lore-dumpster.json and the Anvil's
default font (tools/data/default-font.json, copied from anvil-of-splorr, MIT). Do not hand-edit the outputs:

  src/game/gfx.odin    the Gfx enum and 8x8 pictures (terrain tiles, then sprites), palette indices,
                       0 transparent in sprites
  src/game/font.odin   4x6 cells for ASCII 32..126, one byte per row, leftmost pixel in bit 0x80
  src/game/sounds.odin the Sound enum, in the world's sound order
  web/sounds.js        SOUND_FILES, the WAVs in web/sfx/ in the same order

Run: python3 -I tools/gen_gfx.py   (stdlib only)
After changing sounds in the Anvil, export each to web/sfx/<name>.wav (sound_export) too."""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
world = json.load(open(os.path.join(ROOT, 'art/lore-dumpster.json')))
TW, TH = world['tile_width'], world['tile_height']
assert (TW, TH) == (8, 8), (TW, TH)


def title(name):
    return '_'.join(p.capitalize() for p in name.split('_'))


def unpack(b):
    px = []
    for byte in b:
        px += [byte >> 4, byte & 15]
    assert len(px) == 64
    return px


pics = []
for tsname in ('terrain', 'sprites'):
    ts = next(t['tileset'] for t in world['tilesets'] if t['name'] == tsname)
    for im in ts['images']:
        pics.append((im['name'], unpack(im['bytes'])))
names = [n for n, _ in pics]
assert len(set(names)) == len(names), 'picture names must be unique across tilesets'

out = ["// Generated by tools/gen_gfx.py from art/lore-dumpster.json (the Anvil). Do not hand-edit.",
       "// Drawn by Claude (an AI agent) in the Anvil for Lore Dumpster of SPLORR!!.",
       "package game", "", "Gfx :: enum u8 {"]
out += [f"\t{title(n)}," for n in names]
out += ["}", "", "// 8x8 palette indices per picture, row by row; 0 is transparent (sprites only).",
        f"GFX := [Gfx][64]u8{{"]
for n, px in pics:
    out.append(f"\t.{title(n)} = {{")
    for y in range(8):
        out.append("\t\t" + ", ".join(str(v) for v in px[y * 8:(y + 1) * 8]) + ",")
    out.append("\t},")
out.append("}\n")
open(os.path.join(ROOT, 'src/game/gfx.odin'), 'w').write("\n".join(out))

font = json.load(open(os.path.join(ROOT, 'tools/data/default-font.json')))
assert font['height'] == 6
lines = ["// Generated by tools/gen_gfx.py from tools/data/default-font.json (the Anvil's default font). Do not hand-edit.",
         "package game", "", "GLYPH_W :: 4", "GLYPH_H :: 6", "",
         "// ASCII 32..126; one byte per row, leftmost pixel in bit 0x80.",
         "FONT := [95][6]u8{"]
for code in range(32, 127):
    g = font['glyphs'].get(str(code))
    rows = g['bytes'] if g else [0] * 6
    assert g is None or g['width'] == 4
    lines.append("\t{" + ", ".join(f"0x{r:02X}" for r in rows) + f"}}, // {chr(code)!r}")
lines.append("}\n")
open(os.path.join(ROOT, 'src/game/font.odin'), 'w').write("\n".join(lines))

sounds = [s['name'] for s in world['sounds']]
open(os.path.join(ROOT, 'src/game/sounds.odin'), 'w').write("\n".join(
    ["// Generated by tools/gen_gfx.py from art/lore-dumpster.json. Do not hand-edit.",
     "// Order matches SOUND_FILES in web/sounds.js.", "package game", "", "Sound :: enum u8 {"] +
    [f"\t{title(s)}," for s in sounds] + ["}", ""]))
open(os.path.join(ROOT, 'web/sounds.js'), 'w').write(
    "// Generated by tools/gen_gfx.py. Order matches the Sound enum (src/game/sounds.odin).\n"
    "const SOUND_FILES = [" + ", ".join(f'"sfx/{s}.wav"' for s in sounds) + "];\n")
for s in sounds:
    assert os.path.exists(os.path.join(ROOT, 'web/sfx', s + '.wav')), 'missing web/sfx/' + s + '.wav'
print(f"{len(pics)} pictures, 95 glyphs, {len(sounds)} sounds")
